// Insurance policy register, extracted from the policy PDFs held in the
// company Google Drive (one folder per bus). Picking a bus in the claim
// journey fills these details in, so staff never retype a policy number,
// engine or chassis number off a document.
//
// `validTo` is the policy expiry. The claim journey compares it against the
// date of loss and warns when the policy on file did not cover that date --
// filing against a lapsed policy is the costliest mistake in this workflow.

