/** Compare registrations ignoring spaces and dashes. */
function key(reg: string): string {
  return reg.replace(/[^A-Za-z0-9]/g, "").toUpperCase();
}

/** The policy on file for a registration, however it was typed. */
export function findPolicy(reg: string): Policy | undefined {
  const k = key(reg);
  return POLICIES.find((p) => key(p.reg) === k);
}

/**
 * Whether the policy on file covered a given date of loss.
 * Returns null when either date is missing -- the UI then stays quiet
 * rather than showing a warning it cannot justify.
 */
export function coversDate(policy: Policy, isoDate: string): boolean | null {
  if (!isoDate || !policy.validFrom || !policy.validTo) return null;
  return isoDate >= policy.validFrom && isoDate <= policy.validTo;
}
